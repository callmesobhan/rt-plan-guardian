"""Human-readable rule catalog, generated from the registry (so docs cannot drift from code)."""

from __future__ import annotations

import json

from .rules import CATEGORY_ORDER, REGISTRY

CATEGORY_TITLES = {
    "input": "Input completeness",
    "identity": "Patient identity",
    "linkage": "Cross-object linkage",
    "structure": "Structure set",
    "plan": "Plan & prescription",
    "beam": "Beams & delivery (photon, electron, ion)",
    "ion": "Proton / ion beams",
    "electron": "Electron beams",
    "brachy": "Brachytherapy",
    "dose": "Dose",
    "protocol": "Protocol compliance (ruleset-driven)",
}


def catalog_table() -> str:
    """Plain-text table for the terminal."""
    rows = [(rid, c.category, c.default_severity.value, c.title) for rid, c in REGISTRY.items()]
    w_id = max(len(r[0]) for r in rows)
    w_cat = max(len(r[1]) for r in rows)
    lines = [f"{'ID':<{w_id}}  {'CATEGORY':<{w_cat}}  {'SEVERITY':<8}  TITLE"]
    lines += [f"{rid:<{w_id}}  {cat:<{w_cat}}  {sev:<8}  {title}" for rid, cat, sev, title in rows]
    return "\n".join(lines)


def catalog_markdown() -> str:
    out = [
        "# Rule catalog",
        "",
        "> Generated by `rtpg rules --format md` - do not edit by hand "
        "(a test fails if this file is out of date).",
        "",
        f"{len(REGISTRY)} built-in rules. Severity shown is the default; rulesets may override it. "
        "`requires` lists the DICOM-RT objects that must be supplied, otherwise the rule is reported as SKIPPED.",
        "",
    ]
    for category in CATEGORY_ORDER:
        rules = [c for c in REGISTRY.values() if c.category == category]
        if not rules:
            continue
        out += [f"## {CATEGORY_TITLES[category]}", ""]
        for c in rules:
            out += [
                f"### {c.id} - {c.title}",
                "",
                c.description,
                "",
                f"- **Default severity:** {c.default_severity.value}",
                f"- **Requires:** {', '.join(k.upper() for k in c.requires) or 'nothing'}",
                f"- **Applies to:** {', '.join(sorted(c.applies_to)) or 'every plan'}",
            ]
            if c.reference:
                out.append(f"- **Reference:** {c.reference}")
            if c.default_params:
                out.append("- **Parameters (defaults):**")
                out += [f"  - `{k}`: `{json.dumps(v)}`" for k, v in c.default_params.items()]
            out.append("")
    return "\n".join(out)


def _yaml_flow(value: object) -> str:
    """Flow-style YAML that PyYAML (YAML 1.1) reads back with the right types - notably floats
    in exponent form need a dot ('1.0e-06', not '1e-06')."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        text = repr(value)
        if "e" in text and "." not in text.split("e")[0]:
            mantissa, exponent = text.split("e")
            text = f"{mantissa}.0e{exponent}"
        return text
    if isinstance(value, dict):
        return (
            "{"
            + ", ".join(f"{json.dumps(str(k))}: {_yaml_flow(v)}" for k, v in value.items())
            + "}"
        )
    if isinstance(value, list | tuple):
        return "[" + ", ".join(_yaml_flow(v) for v in value) + "]"
    return json.dumps(value)


def template_yaml() -> str:
    """A ruleset listing EVERY rule with its default severity and parameters (generated)."""
    out = [
        "# Template listing EVERY rule with its default severity and parameters.",
        "# Generated by `rtpg rules --format yaml` - do not edit by hand (a test fails if it is stale).",
        "# Copy this file, delete what you do not want to change, and tune the rest. Rules you remove",
        "# still run with these defaults. Add `extends: aapm_mppg11a` (or any built-in/file ruleset)",
        "# under `ruleset:` to inherit another profile and override single rules or parameters.",
        "#",
        "# THESE ARE LIBRARY DEFAULTS, NOT CLINICAL STANDARDS.",
        "",
        "ruleset:",
        "  name: My clinic ruleset",
        '  version: "1.0.0"',
        "  description: Describe who owns and approved this file.",
        "  # sources:            # cite the documents your limits come from; reports embed them",
        '  #   - "Author et al. Title. Journal Year;vol:pages. doi:..."',
        "",
        "rules:",
    ]
    for category in CATEGORY_ORDER:
        rules = [c for c in REGISTRY.values() if c.category == category]
        if not rules:
            continue
        out += [
            "",
            f"  # --- {CATEGORY_TITLES[category]} "
            + "-" * max(4, 70 - len(CATEGORY_TITLES[category])),
        ]
        for c in rules:
            params = f", params: {_yaml_flow(dict(c.default_params))}" if c.default_params else ""
            out.append(f"  {c.id}: {{ severity: {c.default_severity.value}{params} }}  # {c.title}")
    return "\n".join(out) + "\n"
